// Centroide geográfico real calculado desde los polígonos de cada sector
// Debe ir DESPUÉS de ZONE_POLYGONS y BARRIO_SECTOR para evitar TDZ
function computeSectorCentroids(): Record<Sector, [number, number]> {
  const acc: Record<string, { lat: number; lng: number; n: number }> = {};
  for (const [id, coords] of Object.entries(ZONE_POLYGONS)) {
    const sector = BARRIO_SECTOR[id];
    if (!sector || coords.length === 0) continue;
    if (!acc[sector]) acc[sector] = { lat: 0, lng: 0, n: 0 };
    for (const [lat, lng] of coords) {
      acc[sector].lat += lat;
      acc[sector].lng += lng;
      acc[sector].n++;
    }
  }
  return Object.fromEntries(
    Object.entries(acc).map(([s, { lat, lng, n }]) => [s, [lat / n, lng / n]])
  ) as Record<Sector, [number, number]>;
}
// Posiciones manuales repartidas en los 4 cuadrantes del mapa para evitar solapamiento
const SECTOR_CENTROID: Record<Sector, [number, number]> = {
  Norte:     [6.44, -75.51],
  Sur:       [5.99, -75.61],
  Oriente:   [6.11, -75.40],
  Occidente: [6.41, -75.83],
};

export default function InversionistasLeafletMap({ activeSector, hoveredSector, onSectorHover, onSectorClick, onZoneNavigate }: Props) {
  const containerRef     = useRef<HTMLDivElement>(null);
  const mapRef           = useRef<any>(null);
  const polygonsRef      = useRef<Record<string, { polygon: any }>>({});
  const sectorMarkersRef = useRef<Record<string, any>>({});
  const prevSectorRef      = useRef<Sector | null>(null);
  const onHoverRef         = useRef(onSectorHover);
  const onClickRef         = useRef(onSectorClick);
  const onNavigateRef      = useRef(onZoneNavigate);
  const hoverTimerRef      = useRef<any>(null);
  const userInteractedRef  = useRef(false);
  useEffect(() => { onHoverRef.current = onSectorHover; }, [onSectorHover]);
  useEffect(() => { onClickRef.current = onSectorClick; }, [onSectorClick]);
  useEffect(() => { onNavigateRef.current = onZoneNavigate; }, [onZoneNavigate]);

  useEffect(() => {
    if (!document.querySelector('link[href*="leaflet"]')) {
      const link = document.createElement('link');
      link.rel  = 'stylesheet';
      link.href = 'https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.min.css';
      document.head.appendChild(link);
    }

    const init = () => {
      if (!containerRef.current || mapRef.current) return;
      const L = (window as any).L;

      mapRef.current = L.map(containerRef.current, {
        zoomControl:        true,
        scrollWheelZoom:    false,
        attributionControl: false,
        dragging:           true,
        doubleClickZoom:    true,
        touchZoom:          true,
      }).setView([6.25, -75.58], 9);

      L.tileLayer('https://{s}.basemaps.cartocdn.com/light_all/{z}/{x}/{y}{r}.png', {
        maxZoom: 19,
      }).addTo(mapRef.current);

      // Cuando el usuario hace zoom o pan manual, desactivar auto-fly
      mapRef.current.on('dragstart zoomstart', () => {
        userInteractedRef.current = true;
      });

      for (const [id, coords] of Object.entries(ZONE_POLYGONS)) {
        if (coords.length < 3) continue;

        const polygon = L.polygon(coords, {
          color: '#ccc', weight: 0.5, smoothFactor: 0,
          fillColor: '#ccc', fillOpacity: 0.15, opacity: 0.5,
        }).addTo(mapRef.current);

        const sector = BARRIO_SECTOR[id];
        polygon.on('mouseover', () => {
          clearTimeout(hoverTimerRef.current);
          if (sector) onHoverRef.current?.(sector);
        });
        polygon.on('mouseout', () => {
          hoverTimerRef.current = setTimeout(() => onHoverRef.current?.(null), 60);
        });
        polygon.on('click', () => {
          if (sector) {
            onClickRef.current?.(sector);
            onNavigateRef.current?.(sector);
          }
        });

        polygonsRef.current[id] = { polygon };
      }

      // Colorear polígonos con rojo sutil desde el inicio
      for (const entry of Object.values(polygonsRef.current)) {
        entry.polygon.setStyle({ color: 'transparent', weight: 0, fillColor: RED, fillOpacity: 0.10, opacity: 0 });
      }

      // Marcadores de estadísticas por sector
      const makeSectorIcon = (sector: Sector, isActive: boolean) => {
        const stats = SECTOR_STATS[sector];
        const F = "'Avenir LT Std','Outfit',sans-serif";
        if (isActive) {
          // Estado activo: grande, texto blanco sobre el mapa
          return L.divIcon({
            className: '',
            html: `<div style="transform:translate(-50%,-50%);text-align:center;pointer-events:none;white-space:nowrap;line-height:1">
              <div style="font-family:${F};font-size:42px;font-weight:900;color:#fff;line-height:0.9;text-shadow:0 2px 14px rgba(0,0,0,0.5);white-space:nowrap">${stats.barrios} Barrios</div>
              <div style="font-family:${F};font-size:22px;font-weight:700;color:#fff;line-height:0.9;text-shadow:0 2px 10px rgba(0,0,0,0.45);margin-top:2px;white-space:nowrap">${stats.municipios} Municipios</div>
              <div style="font-family:${F};font-size:11px;font-weight:700;color:#fff;background:${RED};padding:3px 11px;margin-top:4px;white-space:nowrap;display:inline-block;border-radius:0">${stats.propiedades} propiedades</div>
            </div>`,
            iconSize:   [0, 0],
            iconAnchor: [0, 0],
          });
        }
        // Estado por defecto — tarjeta con todos los datos, siempre visible
        return L.divIcon({
          className: '',
          html: `<div style="transform:translate(-50%,-50%);background:rgba(255,255,255,0.30);backdrop-filter:blur(4px);border:1px solid rgba(255,255,255,0.65);border-radius:0;padding:6px 9px 5px;text-align:center;pointer-events:none;min-width:92px;line-height:1">
            <div style="font-family:${F};font-size:10px;font-weight:800;color:#1a1a1a;margin-bottom:5px;letter-spacing:0.06em;text-transform:uppercase">${sector}</div>
            <div style="display:flex;justify-content:center;gap:6px;align-items:flex-start">
              <div>
                <div style="font-family:${F};font-size:17px;font-weight:900;color:${RED};line-height:1">${stats.barrios}</div>
                <div style="font-family:${F};font-size:7px;font-weight:600;color:#444;margin-top:2px;text-transform:uppercase;letter-spacing:0.05em">barrios</div>
              </div>
              <div style="width:1px;background:rgba(0,0,0,0.18);height:24px;flex-shrink:0;margin-top:2px"></div>
              <div>
                <div style="font-family:${F};font-size:17px;font-weight:900;color:#1a1a1a;line-height:1">${stats.municipios}</div>
                <div style="font-family:${F};font-size:7px;font-weight:600;color:#444;margin-top:2px;text-transform:uppercase;letter-spacing:0.05em">munic.</div>
              </div>
              <div style="width:1px;background:rgba(0,0,0,0.18);height:24px;flex-shrink:0;margin-top:2px"></div>
              <div>
                <div style="font-family:${F};font-size:17px;font-weight:900;color:#1a1a1a;line-height:1">${stats.propiedades}</div>
                <div style="font-family:${F};font-size:7px;font-weight:600;color:#444;margin-top:2px;text-transform:uppercase;letter-spacing:0.05em">prop.</div>
              </div>
            </div>
          </div>`,
          iconSize:   [0, 0],
          iconAnchor: [0, 0],
        });
      };

      for (const s of Object.keys(SECTOR_CENTROID) as Sector[]) {
        const pos    = SECTOR_CENTROID[s];
        const marker = L.marker(pos, {
          icon:        makeSectorIcon(s, false),
          interactive: false,
          zIndexOffset: 1000,
        }).addTo(mapRef.current);
        marker.setOpacity(1); // siempre visible
        sectorMarkersRef.current[s] = { marker, makeSectorIcon };
      }
    };

    if ((window as any).L) {
      init();
    } else {
      const script  = document.createElement('script');
      script.src    = 'https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.min.js';
      script.onload = init;
      document.head.appendChild(script);
    }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => {
    const map = mapRef.current;
    if (!map) return;

    const effectiveSector = hoveredSector ?? activeSector;

    for (const [id, refs] of Object.entries(polygonsRef.current)) {
      const sector        = BARRIO_SECTOR[id];
      const inActive      = !effectiveSector || sector === effectiveSector;
      const isHov         = hoveredSector !== null && sector === hoveredSector;
      // Relleno fuerte cuando un sector está activo sin hover (auto-rotación o clic en mobile)
      const isAutoActive  = activeSector !== null && hoveredSector === null && sector === activeSector;

      if (isHov) {
        refs.polygon.setStyle({ color: 'transparent', weight: 0, fillColor: RED, fillOpacity: 0.22, opacity: 0 });
      } else if (isAutoActive) {
        refs.polygon.setStyle({ color: 'transparent', weight: 0, fillColor: RED, fillOpacity: 0.38, opacity: 0 });
      } else if (inActive) {
        refs.polygon.setStyle({ color: 'transparent', weight: 0, fillColor: RED, fillOpacity: 0.12, opacity: 0 });
      } else {
        refs.polygon.setStyle({ color: '#bbb', weight: 0.5, fillColor: '#bbb', fillOpacity: 0.12, opacity: 0.5 });
      }
    }

    // Cuando hay sector activo/hover, mostrar solo ese marcador — elimina solapamiento
    for (const [s, ref] of Object.entries(sectorMarkersRef.current)) {
      if (!ref || !ref.marker || typeof ref.marker.setOpacity !== 'function') continue;
      const isActive = effectiveSector !== null && s === effectiveSector;
      try {
        if (effectiveSector !== null) {
          ref.marker.setOpacity(isActive ? 1 : 0);
        } else {
          ref.marker.setOpacity(1);
        }
        if (typeof ref.makeSectorIcon === 'function') {
          ref.marker.setIcon(ref.makeSectorIcon(s as Sector, isActive));
        }
      } catch (_) { /* marker puede estar en estado parcial durante inicialización */ }
    }

    const targetSector = hoveredSector ?? activeSector;
    if (targetSector !== prevSectorRef.current) {
      prevSectorRef.current = targetSector;
      // Solo fly automático si el usuario no ha hecho zoom/pan manual
      // Nunca volver al overview automáticamente (quita el snap-back)
      if (targetSector && !userInteractedRef.current) {
        const v = SECTOR_VIEW[targetSector];
        map.flyTo(v.center, v.zoom, { duration: 0.7, easeLinearity: 0.5 });
      }
    }
  }, [activeSector, hoveredSector]);

  return <div ref={containerRef} style={{ width: '100%', height: '100%' }} />;
}
